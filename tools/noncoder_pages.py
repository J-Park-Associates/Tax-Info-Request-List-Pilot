_DATED_NAME = re.compile(r"\d{4}-\d{2}-\d{2} .+\.md")
_DATE = re.compile(r"\d{4}-\d{2}-\d{2}")


def _title(stem: str) -> str:
    return re.sub(r"[-_]+", " ", stem).strip().title()


def _next_number(folder: Path, pattern: str) -> int:
    numbers = [int(m[1]) for p in folder.glob("*.md") if (m := re.match(pattern, p.name))]
    return max(numbers, default=0) + 1


def _stage_folder(root: Path, number: str) -> Path:
    folders = sorted(p for p in (root / LIBRARY / WORK_HISTORY).glob(f"Stage {number} - *") if p.is_dir())
    if not folders:
        raise LibraryError(f"no folder for stage {number} under {LIBRARY}/{WORK_HISTORY}: a person must "
                           f"name one (Stage {number} - <plain name>) before it gets a page")
    return folders[0]


def _note_date(root: Path, note: str, today: datetime.date | None) -> str:
    source = Path(note) if Path(note).is_absolute() else root / note
    if source.is_file():
        for line in source.read_text(encoding="utf-8").splitlines():
            if found := _DATE.search(line):
                return found[0]
    return (today or datetime.date.today()).isoformat()


def place(root: Path, note: str, today: datetime.date | None = None) -> str:
    """Where a new handoff note's page belongs, repository-relative; deterministic, from the file name.

    Reproduces the library's layout: stage folders in order, the final checks numbered, the rulings
    unnumbered, anything else under Other Work with the note's own date."""
    name = Path(note).name
    stem = name[:-3] if name.endswith(".md") else name
    base = f"{LIBRARY}/{WORK_HISTORY}"
    if m := _STAGE_NOTE.fullmatch(stem):
        number, letter, family, k = m.groups()
        folder = _stage_folder(root, number)
        prefix = f"S{number}{letter}"
        label = "Build" if family is None else f"Review {k}" if family == "review" else f"Fix Round {k}"
        n = _next_number(folder, rf"{re.escape(prefix)} - (\d+) ")
        return f"{base}/{folder.name}/{prefix} - {n:02d} {label}.md"
    bare = stem.removeprefix("shell-")
    if stem.startswith(("shell-final-", "shell-fixpass")):
        n = _next_number(root / LIBRARY / WORK_HISTORY / "Final Checks", r"(\d+) ")
        return f"{base}/Final Checks/{n} {_title(bare)}.md"
    if stem.startswith(("shell-rulings", "shell-ledger", "shell-spec-sync")):
        return f"{base}/Jason's Rulings and Plan Updates/{_title(bare)}.md"
    return f"{base}/Other Work/{_note_date(root, note, today)} {_title(stem)}.md"


