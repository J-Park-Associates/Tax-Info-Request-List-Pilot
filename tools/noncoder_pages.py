def findings(root: Path) -> list[Finding]:
    """Everything wrong with the library, sorted; never writes."""
    paths = page_paths(root)
    pages = [parse_page(root, p) for p in paths]
    record = load_record(root)
    out: list[Finding] = []
    named = {o for page in pages for o in page.originals}
    for note in note_paths(root):
        if note not in named:
            try:
                where = place(root, note)
            except LibraryError as exc:
                out.append(Finding("missing", "", (note,), f"{note} has no plain-English page, and {exc}.",
                                   "a person creates or names the stage folder; then write the page, "
                                   "run organize and stamp it"))
                continue
            out.append(Finding("missing", where, (note,), f"{note} has no plain-English page.",
                               f"write the page at {where}, then stamp it"))
    for page in pages:
        for problem in page.problems:
            out.append(Finding("malformed", page.path, page.originals, f"{page.path}: {problem}.",
                               f"fix the page against {STYLE_FILE}"))
        held = record.get(page.path, {}).get("originals", {})
        for original in page.originals:
            if not (root / original).is_file() and _in_head(root, original):
                out.append(Finding("missing", page.path, (original,),
                                   f"original {original} is missing but not removed in Git: if it was renamed, "
                                   f"fix the page's Original file line; if it was deleted, commit the deletion.",
                                   f"fix {page.path}'s Original file line, or commit the deletion"))
            if (root / original).is_file() and held.get(original) != fingerprint(root / original):
                how = "has no recorded fingerprint" if original not in held else "changed after its page was stamped"
                out.append(Finding("stale", page.path, (original,), f"{page.path}: original {original} {how}.",
                                   f"update the page (or confirm it is still accurate), then "
                                   f"python tools/noncoder_pages.py stamp '{page.path}'"))
    by_path = {p.path: p for p in pages}
    for path, held in sorted(record.items()):
        if path not in by_path:
            out.append(Finding("orphan", "", (), f"pages.json records {path}, which is no longer a page.",
                               "python tools/noncoder_pages.py stamp"))
        else:
            for original in sorted(set(held["originals"]) - set(by_path[path].originals)):
                out.append(Finding("orphan", "", (original,),
                                   f"pages.json records {original} for {path}, which the page no longer names.",
                                   "python tools/noncoder_pages.py stamp"))
    for leftover in sorted((root / LIBRARY).rglob("*.organize-*")):
        rel = leftover.relative_to(root).as_posix()
        out.append(Finding("organize", rel, (), f"{rel} is left over from an organize that failed part way.",
                           "rename it back by hand: drop the '.organize-N' ending"))
    for path in history_paths(root):
        first = (root / path).read_text(encoding="utf-8").split("\n", 1)[0]
        if not first.startswith("# "):
            out.append(Finding("malformed", path, (), f"{path}: the first line is not a '# ' title.",
                               "start the history page with its '# ' title"))
    start = root / START_PAGE
    if not start.is_file() or start.read_bytes().replace(b"\r\n", b"\n") != \
            render_start(pages, history_entries(root)).encode("utf-8"):
        out.append(Finding("start", "", (), f"{START_PAGE} does not match what the pages' tags generate.",
                           "python tools/noncoder_pages.py stamp"))
    return sorted(out)


def work_order(found: list[Finding], limit: int | None = None) -> str:
    """The findings as a work order an agent can follow: the page, the originals, the style file."""
    shown = found if limit is None else found[:limit]
    lines: list[str] = []
    for n, f in enumerate(shown, 1):
        lines.append(f"{n}. [{f.kind}] {f.problem}")
        if f.page:
            lines.append(f"   page: {f.page}")
        if f.originals:
            lines.append(f"   read: {', '.join(f.originals)}")
        lines.append(f"   do: {f.fix}")
    if limit is not None and len(found) > limit:
        lines.append(f"... and {len(found) - limit} more (run: python tools/noncoder_pages.py todo)")
    lines.append(f"Style rules for every page: {STYLE_FILE}. Write in plain words; never invent a fact.")
    return "\n".join(lines)


