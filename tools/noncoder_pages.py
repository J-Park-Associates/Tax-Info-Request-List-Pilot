def hook(root: Path, stdin_text: str) -> tuple[int, str, str]:
    """The Stop hook: ``(exit code, stdout, stderr)``.

    It runs ``organize`` first - the mechanical part fixes itself - then ``check``. Pages it moved are
    listed, with the order to stage them and refresh the code map. Exit 2 with the work order on stderr keeps a Claude Code session going with that text
    as its instruction; an organize refusal is a finding in it. A session that already tried once
    (``stop_hook_active``) gets a warning on stdout and exit 0, so one that cannot fix the library is
    never trapped; the test and CI still hold the line. A broken hook must never block work, so any
    error is a one-line warning and exit 0."""
    try:
        try:
            active = bool(json.loads(stdin_text or "{}").get("stop_hook_active"))
        except (json.JSONDecodeError, AttributeError):
            active = False
        moved, refused = organize(root, dry_run=active)
        said = "".join(f"{line}\n" for line in moved)
        found = sorted(refused + findings(root))
        text = ""
        if moved:
            text += (said + "The plain-English library organizer moved these pages: stage these moves "
                     "(git add -A \"docs/For NonCoders\") and run python tools/repo_map.py update\n")
        if found:
            text += ("The plain-English library (docs/For NonCoders) is out of date:\n"
                     + work_order(found, HOOK_LIMIT) + "\n")
        if not text:
            return 0, "", ""
        return (0, text, "") if active else (2, "", text)
    except Exception as exc:  # noqa: BLE001 - a broken hook must never block work
        return 0, f"noncoder_pages hook skipped: {type(exc).__name__}\n", ""


# --------------------------------------------------------------------- CLI ----


def main(argv: list[str] | None = None) -> int:
    for stream in (sys.stdout, sys.stderr):        # a Windows console's code page must not crash a report
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("check", help="verify the library is current; exit 1 if not")
    sub.add_parser("todo", help="print what is out of date as a work order")
    stamp_cmd = sub.add_parser("stamp", help="record fingerprints and regenerate the start page")
    stamp_cmd.add_argument("pages", nargs="*", help="pages to stamp (default: all)")
    place_cmd = sub.add_parser("place", help="print where a new handoff note's page belongs")
    place_cmd.add_argument("note")
    organize_cmd = sub.add_parser("organize", help="move and rename pages to where the rules say")
    organize_cmd.add_argument("--dry-run", action="store_true", help="print the moves without making them")
    sub.add_parser("hook", help="the Claude Code Stop hook")
    ns = parser.parse_args(argv)
    try:
        if ns.command == "hook":
            try:
                stdin_text = sys.stdin.read()
            except (OSError, UnicodeDecodeError):
                stdin_text = ""
            code, out, err = hook(ROOT, stdin_text)
            sys.stdout.write(out)
            sys.stderr.write(err)
            return code
        if ns.command == "place":
            print(place(ROOT, ns.note))
            return 0
        if ns.command == "organize":
            moved, refused = organize(ROOT, ns.dry_run)
            if moved:
                print("\n".join(moved))
            for f in refused:
                print(f"refused: {f.problem} {f.fix}", file=sys.stderr)
            return 1 if refused else 0
        if ns.command == "stamp":
            notes: list[str] = []
            left = stamp(ROOT, ns.pages, notes)
            print("\n".join(notes + [f"Stamped {RECORD} and {START_PAGE}."]))
            if left:
                print(f"Still out of date ({len(left)}):\n" + work_order(left))
            return 1 if left else 0
        found = findings(ROOT)
        if ns.command == "todo":
            moved, refused = organize(ROOT, dry_run=True)
            found = sorted(refused + found)
            if moved:
                print("organize would first do (run: python tools/noncoder_pages.py organize):\n" + "\n".join(moved))
            print(work_order(found) if found else "The plain-English library is current; nothing to do.")
            return 0
        if not found:
            print("The plain-English library is current.")
            return 0
        for f in found:
            print(f"[{f.kind}] {f.problem} Fix: {f.fix}")
        return 1
    except LibraryError as exc:
        print(f"noncoder_pages: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
