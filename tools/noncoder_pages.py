def _stage_order(note: str) -> tuple:
    """Build first, then review k and fix round k in turn - the order a stage happened in."""
    m = _STAGE_NOTE.fullmatch(Path(note).stem)
    family, k = m[3], int(m[4] or 0)
    return (0, 0, 0) if family is None else (1, k, 0 if family == "review" else 1)


def _in_head(root: Path, path: str) -> bool | None:
    """Is ``path`` in Git's ``HEAD``? ``None`` when Git cannot say (not installed, not a repository,
    no commit yet), and then nothing is retired: only a committed deletion proves a file is gone."""
    try:
        head = subprocess.run(["git", "rev-parse", "--verify", "-q", "HEAD"], cwd=root,
                              capture_output=True, timeout=30)
        if head.returncode != 0:
            return None
        return subprocess.run(["git", "cat-file", "-e", f"HEAD:{path}"], cwd=root,
                              capture_output=True, timeout=30).returncode == 0
    except (OSError, subprocess.SubprocessError):
        return None


def _removed_in_git(root: Path, path: str) -> bool:
    """Was ``path`` committed once and removed since? Only that proves a page's file is gone: a file
    that is merely missing from the working tree, or was never committed (a new note renamed before
    its first commit), is the agent's to fix on the page, never a retirement (review 2)."""
    if _in_head(root, path) is not False:
        return False
    try:
        seen = subprocess.run(["git", "log", "-1", "--format=%H", "--", path], cwd=root,
                              capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.SubprocessError):
        return False
    return seen.returncode == 0 and bool(seen.stdout.strip())


def _contains_a_name(name: str, originals: tuple[str, ...]) -> bool:
    low = name.lower()
    for original in originals:
        path = Path(original)
        for known in (path.name, path.stem, path.parent.name):
            if known and known.lower() in low:
                return True
    return False


def _targets(root: Path, pages: list[Page], today: datetime.date) -> tuple[dict[str, str], list[Finding]]:
    """Where each page belongs: ``{current path: target path}`` for the pages that must move, and a
    refusal for each that cannot. Pure of side effects; the rules of section 9.1 in order."""
    moves: dict[str, str] = {}
    refused: list[Finding] = []
    lib = LIBRARY + "/"
    notes = set(note_paths(root))
    stage_groups: dict[tuple[str, str], list[tuple[tuple, str, Page]]] = {}
    numbered: dict[str, int] = {}
    for page in pages:
        name = Path(page.path).name
        if page.originals and not any((root / o).is_file() for o in page.originals) \
                and all(_removed_in_git(root, o) for o in page.originals):
            moves[page.path] = f"{lib}{ARCHIVE}/{RETIRED}/{page.path[len(lib):]}"
            continue
        note = next((o for o in page.originals if o in notes), None)
        if page.kind == "Overview":
            moves[page.path] = f"{lib}{START}/{name}"
        elif page.kind == PROGRAM_KIND and page.topics and page.topics[0] in PROGRAM_HOMES:
            section, default = PROGRAM_HOMES[page.topics[0]]
            inside = page.path.startswith(f"{lib}{section}/")
            folder = Path(page.path).parent.as_posix() if inside else f"{lib}{section}/{default}".rstrip("/")
            if not _contains_a_name(name, page.originals):
                name = f"{Path(page.path).stem} ({Path(page.originals[0]).name}).md"
            moves[page.path] = f"{folder}/{name}"
        elif page.kind in KINDS and page.kind != PROGRAM_KIND and note is not None:
            stem = Path(note).stem
            if m := _STAGE_NOTE.fullmatch(stem):
                try:
                    folder = _stage_folder(root, m[1])
                except LibraryError as exc:
                    refused.append(Finding("organize", page.path, (note,), f"{page.path}: {exc}.",
                                           "a person names the stage folder; then run organize"))
                    continue
                shape = _STAGE_NAME.fullmatch(name)
                label = shape["label"] if shape else \
                    ("Build" if m[3] is None else f"Review {m[4]}" if m[3] == "review" else f"Fix Round {m[4]}")
                stage_groups.setdefault((folder.relative_to(root).as_posix(), f"S{m[1]}{m[2]}"), []) \
                    .append((_stage_order(note), label, page))
            elif stem.startswith(("shell-final-", "shell-fixpass")):
                folder = f"{lib}{WORK_HISTORY}/Final Checks"
                if not _FINAL_NAME.fullmatch(name):
                    numbered[folder] = numbered.get(folder, _next_number(root / folder, r"(\d+) ") - 1) + 1
                    name = f"{numbered[folder]} {_title(stem.removeprefix('shell-'))}.md"
                moves[page.path] = f"{folder}/{name}"
            elif stem.startswith(("shell-rulings", "shell-ledger", "shell-spec-sync")):
                moves[page.path] = f"{lib}{WORK_HISTORY}/Jason's Rulings and Plan Updates/{name}"
            else:
                if not _DATED_NAME.fullmatch(name):
                    name = f"{_note_date(root, note, today)} {_title(stem)}.md"
                moves[page.path] = f"{lib}{WORK_HISTORY}/Other Work/{name}"
    for (folder, prefix), members in stage_groups.items():
        for n, (_, label, page) in enumerate(sorted(members, key=lambda m: (m[0], m[2].path)), 1):
            moves[page.path] = f"{folder}/{prefix} - {n:02d} {label}.md"
    return {src: dst for src, dst in moves.items() if src != dst}, refused


def organize(root: Path, dry_run: bool = False, today: datetime.date | None = None) -> tuple[list[str], list[Finding]]:
    """Move and rename pages to where the rules say; returns the lines to say and the refusals.

    Never edits a page but for the Retired line, never overwrites a file, and carries a moved page's
    record in ``pages.json`` to its new path (its originals did not change, so it is no staler than
    before). A page whose file was removed is retired. With ``dry_run`` nothing changes."""
    today = today or datetime.date.today()
    pages = [parse_page(root, p) for p in page_paths(root)]
    moves, refused = _targets(root, pages, today)
    staying = {p.path for p in pages} - set(moves)
    claimed: dict[str, list[str]] = {}
    for src, dst in moves.items():
        claimed.setdefault(dst, []).append(src)
    ok: dict[str, str] = {}
    for src, dst in sorted(moves.items()):
        if len(claimed[dst]) > 1 or dst in staying or ((root / dst).exists() and dst not in moves):
            refused.append(Finding("organize", src, (), f"{src} belongs at {dst}, which is taken by a different file.",
                                   "rename or merge one of the two pages by hand; organize never overwrites"))
        else:
            ok[src] = dst
    lines = [f"{'would move' if dry_run else 'moved'}: {src} -> {dst}" for src, dst in sorted(ok.items())]
    if dry_run or not ok:
        return lines, sorted(refused)
    record = load_record(root) if (root / RECORD).is_file() else {}
    undo: list[tuple[Path, Path]] = []                         # (where it is now, where it came from)
    restore: dict[Path, bytes] = {}                            # a retired page's text before its Retired line
    try:
        for n, src in enumerate(sorted(ok)):                   # two phases, so a chain of renames cannot collide
            (root / src).rename(root / f"{src}.organize-{n}")
            undo.append((root / f"{src}.organize-{n}", root / src))
        for n, (src, dst) in enumerate(sorted(ok.items())):
            target = root / dst
            target.parent.mkdir(parents=True, exist_ok=True)
            (root / f"{src}.organize-{n}").rename(target)
            undo[n] = (target, root / src)
        for src, dst in sorted(ok.items()):
            if dst.startswith(f"{LIBRARY}/{ARCHIVE}/{RETIRED}/"):
                restore[root / dst] = (root / dst).read_bytes()
                _write_retired_line(root / dst, today)
                record.pop(src, None)
    except Exception as exc:
        stuck = _roll_back(undo, restore)                      # a half-done organize is worse than none
        said = ("every rename already made was put back where it was" if not stuck else
                "these could not be put back and are named here so nothing is lost: " + "; ".join(stuck))
        raise LibraryError(f"organize failed ({type(exc).__name__}: {exc}); {said}") from exc
    for src, dst in ok.items():
        if src in record:
            record[dst] = record.pop(src)
    if record or (root / RECORD).is_file():
        (root / RECORD).write_bytes(render_record(record))
    for src in ok:                                            # empty folders a move left behind
        folder = (root / src).parent
        while folder != root / LIBRARY and folder.is_dir() and not any(folder.iterdir()):
            folder.rmdir()
            folder = folder.parent
    pages = [parse_page(root, p) for p in page_paths(root)]
    (root / START_PAGE).write_bytes(render_start(pages, history_entries(root)).encode("utf-8"))
    return lines, sorted(refused)


def _roll_back(undo: list[tuple[Path, Path]], restore: dict[Path, bytes]) -> list[str]:
    """Put every page back, in two phases like the move itself, so two pages that swapped names can
    never land on each other, and never over an existing file (``rename`` would overwrite one on
    POSIX). Returns a sentence for each page it could not put back, naming where it now is."""
    stuck: list[str] = []
    parked: list[tuple[Path, Path]] = []
    for n, (now, was) in enumerate(undo):
        try:
            if now in restore:
                now.write_bytes(restore[now])
            aside = now.with_name(f"{now.name}.organize-undo-{n}")
            if aside.exists():
                raise FileExistsError(aside)
            now.rename(aside)
            parked.append((aside, was))
        except OSError as exc:
            stuck.append(f"{now} (meant for {was}: {type(exc).__name__})")
    for aside, was in parked:
        try:
            if was.exists():
                raise FileExistsError(was)
            aside.rename(was)
        except OSError as exc:
            stuck.append(f"{aside} (meant for {was}: {type(exc).__name__})")
    return stuck


def _write_retired_line(path: Path, today: datetime.date) -> None:
    """The one text edit organize makes: say, after the Tags line, that the original is gone."""
    lines = path.read_text(encoding="utf-8").split("\n")
    at = next((i for i, ln in enumerate(lines) if ln.startswith("**Tags:**")),
              next((i for i, ln in enumerate(lines) if ln.startswith("**Original file:**")), 0))
    lines.insert(at + 1, f"**Retired:** {today.isoformat()} - the file it explained was removed.  ")
    path.write_bytes("\n".join(lines).encode("utf-8"))


