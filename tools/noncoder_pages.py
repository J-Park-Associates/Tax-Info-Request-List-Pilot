"""Keep the plain-English library honest: ``docs/For NonCoders/`` and its bookkeeping.

The library is a translation of the repository for a reader who does not
write code: one page per program file and per handoff note, each naming the
original it explains. A page is wrong silently in three ways - a new handoff
note arrives with no page, an original changes after its page was written,
or a page is moved or re-tagged and the start page no longer lists it right.
Nothing else in the repository notices any of them, and a translation nobody
re-checks is worse than none, because the owner trusts it.

This tool owns the bookkeeping, the way ``tools/vocab_report.py`` owns its
report. It fingerprints every original (SHA-256, of the bytes Git commits -
``git_text_auto_eol_lf``, the map's rule, decision 151 - so a CRLF working
copy is not stale on a CI checkout) into ``docs/For NonCoders/pages.json``,
generates the start page (``README.md``) from the pages' own Tags lines, and
``check`` fails, naming each page and the exact fix, on any gap. Three
triggers run ``check``, cheapest first: a Claude Code Stop hook (``hook``),
so an AI session that leaves a page stale is told to fix it before it ends;
``tests/test_noncoder_pages.py``, a guard every gate runs; and CI.

Only the bookkeeping is automated. Writing a page stays with the agent: an AI
may read handoff notes and program files (they are not client documents, so
the first standing rule is untouched), and a person can read the diff. The
tool never writes prose and the hook never edits a page - a skeleton would
pass a structural check and say nothing; a hash on each page would churn
with every page edit; a hook that wrote pages would put words in the firm's
mouth that nobody read.

``pages.json`` and ``README.md`` are generated. Never hand-edit either;
``stamp`` is the one way they change, run after a page is written, updated,
or reviewed and found still accurate (``organize`` only carries a moved page's
record to its new path). ``stamp`` also keeps the version a page replaces, in
``7 - History/Earlier Versions``, from Git's ``HEAD``.

The mechanical part fixes itself: ``organize`` moves and renames pages to where
the rules say - a handoff page by its note's name, a program page by its first
topic - retires a page whose original was removed - gone from the working tree and
from Git's ``HEAD``, so a rename is never mistaken for a removal - to
``7 - History/Retired Pages``, and renumbers a stage folder when a note is
inserted. It never edits prose (the one text edit is the Retired line), never
overwrites, and never touches an original: other files and tests cite those
paths. The Stop hook runs it (so the hook does move pages and adds the Retired
line, and never edits a page's prose), then ``check``, so only the writing is
handed back to the agent. A hook that moved pages exits 2 once so the session
stages the moves and refreshes the code map. History is
exempt from the page rules: what a page said then is a record, not a claim.

::

    python tools/noncoder_pages.py check            # is the library current? exit 1 if not
    python tools/noncoder_pages.py todo             # the same findings as a work order (exit 0)
    python tools/noncoder_pages.py organize [--dry-run]   # move and rename pages to where the rules say
    python tools/noncoder_pages.py stamp [PAGE ...] # record fingerprints, regenerate the start page
    python tools/noncoder_pages.py place NOTE       # where a new note's page belongs
    python tools/noncoder_pages.py hook             # the Stop hook (reads its JSON on stdin)
"""

