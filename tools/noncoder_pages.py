def _link(path: str, title: str) -> str:
    return f"[{title}](<{path}>)"


def _title_of(root: Path, path: str) -> str:
    """The first line's title of a history page, or its file name when it has none."""
    lines = (root / path).read_text(encoding="utf-8").splitlines()
    return lines[0][2:].strip() if lines and lines[0].startswith("# ") and lines[0][2:].strip() else Path(path).stem


def history_entries(root: Path) -> dict[str, list[tuple[str, str]]]:
    """The history pages by group (their folder under ``7 - History``) as (library path, title)."""
    groups: dict[str, list[tuple[str, str]]] = {RETIRED: [], EARLIER: []}
    prefix = f"{LIBRARY}/{ARCHIVE}/"
    for path in history_paths(root):
        group = path[len(prefix):].split("/")[0] if "/" in path[len(prefix):] else "Other"
        groups.setdefault(group, []).append((path[len(LIBRARY) + 1:], _title_of(root, path)))
    return {group: sorted(found) for group, found in groups.items()}


def render_start(pages: list[Page], history: dict[str, list[tuple[str, str]]] | None = None) -> str:
    """The start page, from the pages' own Tags lines; a page with broken tags is left out
    (``check`` reports it as malformed). History is listed last, under its own heading."""
    history = history or {RETIRED: [], EARLIER: []}
    prefix = LIBRARY + "/"
    entries = [(p.path[len(prefix):], p.title, p.kind, p.topics, p.stage)
               for p in pages if p.kind in KINDS and all(t in TOPICS for t in p.topics) and p.title]
    by_topic: dict[str, list] = {}
    by_kind: dict[str, list] = {}
    for entry in entries:
        by_kind.setdefault(entry[2], []).append(entry)
        for topic in entry[3]:
            by_topic.setdefault(topic, []).append(entry)
    lines = [
        "# For NonCoders: start here", "",
        "Every page in this folder explains one part of the Tax Document Tracker",
        "in plain words, for a reader who does not write code. Each page names the",
        "original file it explains, so a programmer can find it too.", "",
        "These pages explain; the originals decide. If a page here and its original",
        "ever disagree, the original is right, and this page needs fixing.", "",
        "Start with the [maintenance guide](../maintenance-guide.md), the plain-English",
        f"overview of the whole system, then [where the pilot stands](<{START}/Where the Pilot Stands (main handoff).md>).",
        "", "## How the folders are arranged", "",
        "| Folder | What is in it |", "|---|---|",
        *(f"| `{name}` | {meaning} |" for name, meaning in FOLDERS),
        "", "## What the tags mean", "",
        "Every page has a **Tags** line near the top, with up to three kinds of tag.", "",
        "**Kind** - what sort of page it is:", "",
        "| Kind | Meaning |", "|---|---|",
        *(f"| {kind} | {meaning} |" for kind, meaning in KINDS.items()),
        "", "**Topic** - what part of the system the page is about:", "",
        "| Topic | Meaning |", "|---|---|",
        *(f"| {topic} | {meaning} |" for topic, meaning in TOPICS.items()),
        "", "**Stage** - for work history pages, which build stage of the new screen",
        "(S1 to S8b) the session belonged to. Inside each stage folder the pages are",
        "numbered in the order they happened: build, review 1, fix round 1, review 2,",
        "and so on.", "", "## Every page, by topic", "",
    ]
    for topic in sorted(by_topic):
        lines += [f"### {topic}", ""]
        for path, title, kind, _, stage in sorted(by_topic[topic]):
            lines.append(f"- {_link(path, title)} - {kind}{f' ({stage})' if stage else ''}")
        lines.append("")
    lines += ["## Every page, by kind", ""]
    for kind in KINDS:
        found = sorted(by_kind.get(kind, []))
        lines += [f"### {kind} ({len(found)})", ""]
        lines += [f"- {_link(path, title)}" for path, title, *_ in found]
        lines.append("")
    lines += ["## History", "",
              "Pages whose file was removed, and earlier versions of pages that were rewritten.",
              "They record what a page said then; they are not kept up to date.", ""]
    for group, found in history.items():
        lines += [f"### {group} ({len(found)})", ""]
        lines += [f"- {_link(path, title)}" for path, title in found] or ["- none"]
        lines.append("")
    lines += ["---", "", GENERATED_FOOTER]
    return "\n".join(lines) + "\n"


