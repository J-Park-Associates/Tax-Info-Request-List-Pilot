class LibraryError(Exception):
    """The library could not be read, or a note has nowhere to go."""


@dataclass(frozen=True, slots=True, order=True)
class Finding:
    """One thing wrong with the library, and the one action that fixes it."""

    kind: str          # missing, stale, orphan, malformed, start
    page: str          # repo-relative page to write or update; "" when the fix is `stamp` alone
    originals: tuple[str, ...]
    problem: str
    fix: str


@dataclass(frozen=True, slots=True)
class Page:
    path: str                      # repo-relative, posix
    title: str
    originals: tuple[str, ...]
    kind: str
    topics: tuple[str, ...]
    stage: str | None
    problems: tuple[str, ...]


# ------------------------------------------------------------------ reading ----


def fingerprint(path: Path) -> str:
    """SHA-256 of ``path`` as Git commits it (``git_text_auto_eol_lf``, decision 151)."""
    return hashlib.sha256(git_text_auto_eol_lf(path.read_bytes())).hexdigest()


def page_paths(root: Path) -> list[str]:
    """Every page: each ``*.md`` under the library except its start page and its history."""
    library = root / LIBRARY
    found = (p.relative_to(root).as_posix() for p in library.rglob("*.md"))
    return sorted(p for p in found if p != START_PAGE and not p.startswith(f"{LIBRARY}/{ARCHIVE}/"))


def history_paths(root: Path) -> list[str]:
    """Every page in ``7 - History``: retired pages and earlier versions."""
    return sorted(p.relative_to(root).as_posix() for p in (root / LIBRARY / ARCHIVE).rglob("*.md"))


def note_paths(root: Path) -> list[str]:
    """Every handoff note a page must translate."""
    notes = sorted(p.relative_to(root).as_posix() for p in (root / "pilot" / "handoffs").glob("*.md"))
    return sorted(notes + (["pilot/HANDOFF.md"] if (root / "pilot" / "HANDOFF.md").is_file() else []))


def parse_page(root: Path, path: str) -> Page:
    """A page's title, originals and tags, with every rule of the layout it breaks."""
    text = (root / path).read_text(encoding="utf-8")
    lines = text.splitlines()
    problems: list[str] = []
    title = lines[0][2:].strip() if lines and lines[0].startswith("# ") else ""
    if not title:
        problems.append("the first line is not a '# ' title")
    originals: tuple[str, ...] = ()
    named = next((ln for ln in lines if ln.startswith("**Original file:**")), None)
    if named is None:
        problems.append("no '**Original file:**' line")
    else:
        originals = tuple(re.findall(r"`([^`]+)`", named))
        if not originals:
            problems.append("the Original file line names no file in backticks")
        for original in originals:
            if not (root / original).is_file():
                problems.append(f"original `{original}` is not a file in the repository")
    kind, topics, stage = "", (), None
    tags = next((TAGS_LINE.match(ln) for ln in lines if ln.startswith("**Tags:**")), None)
    if tags is None:
        problems.append("no well-formed '**Tags:** Kind: ... · Topic: ...' line")
    else:
        kind = tags["kind"].strip()
        topics = tuple(t.strip() for t in tags["topics"].split(","))
        stage = tags["stage"]
        if kind not in KINDS:
            problems.append(f"unknown Kind {kind!r} (one of: {', '.join(KINDS)})")
        problems += [f"unknown Topic {t!r} (one of: {', '.join(TOPICS)})" for t in topics if t not in TOPICS]
        if stage is not None and not STAGE_SHAPE.fullmatch(stage):
            problems.append(f"Stage {stage!r} is not S, digits and an optional lowercase letter")
    headings = PROGRAM_HEADINGS if kind == PROGRAM_KIND else HANDOFF_HEADINGS
    present = {ln[3:].strip() for ln in lines if ln.startswith("## ")}
    problems += [f"missing the section '## {h}'" for h in headings if h not in present]
    if len(lines) > MAX_LINES:
        problems.append(f"{len(lines)} lines; the limit is {MAX_LINES}")
    if ONE_TIME_STEP.search(text):
        problems.append("tells a person to do something 'once after installing/upgrading' (decision 209)")
    return Page(path, title, originals, kind, topics, stage, tuple(problems))


def load_record(root: Path) -> dict[str, dict]:
    """``pages.json``'s pages, each ``{"page": <sha256 of the page>, "originals": {path: sha256}}``;
    empty when there is no record yet."""
    path = root / RECORD
    if not path.is_file():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        if data["version"] != SCHEMA_VERSION:
            raise LibraryError(f"{RECORD} is version {data['version']!r}, this tool writes {SCHEMA_VERSION}; "
                               "run: python tools/noncoder_pages.py stamp")
        return {page: {"page": str(entry["page"]), "originals": dict(entry["originals"])}
                for page, entry in data["pages"].items()}
    except (json.JSONDecodeError, KeyError, TypeError, ValueError, AttributeError) as exc:
        raise LibraryError(f"could not read {RECORD} ({type(exc).__name__}); run: "
                           "python tools/noncoder_pages.py stamp") from None


def render_record(pages: dict[str, dict]) -> bytes:
    body = {"version": SCHEMA_VERSION, "pages": pages}
    return (json.dumps(body, indent=2, sort_keys=True, ensure_ascii=False) + "\n").encode("utf-8")


