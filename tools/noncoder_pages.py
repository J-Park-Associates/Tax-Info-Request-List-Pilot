def _keep_earlier(root: Path, page: str, recorded: str, today: datetime.date) -> str:
    """Write the version a page replaces to ``7 - History/Earlier Versions``, taken from Git's ``HEAD``
    when ``HEAD`` still holds exactly the text that was stamped. Returns the one line to say."""
    try:
        shown = subprocess.run(["git", "show", f"HEAD:{page}"], cwd=root, capture_output=True,
                               check=True, timeout=30).stdout
    except (OSError, subprocess.SubprocessError):
        return f"no earlier version of {page} kept: Git has no HEAD version of it"
    if hashlib.sha256(git_text_auto_eol_lf(shown)).hexdigest() != recorded:
        return f"no earlier version of {page} kept: HEAD holds a version that was never stamped"
    folder = root / LIBRARY / ARCHIVE / EARLIER
    folder.mkdir(parents=True, exist_ok=True)
    stem = f"{Path(page).stem} - until {today.isoformat()}"
    target, n = folder / f"{stem}.md", 1
    while target.exists():
        n += 1
        target = folder / f"{stem} ({n}).md"
    target.write_bytes(shown)
    return f"kept the earlier version of {page} as {target.relative_to(root).as_posix()}"


def stamp(root: Path, only: list[str] | None = None, notes: list[str] | None = None,
          today: datetime.date | None = None) -> list[Finding]:
    """Record the fingerprints of the given pages' originals (all pages when none), keep the version
    each rewritten page replaces, regenerate the start page, and return what is still wrong. With no
    pages given the record is rebuilt whole, which is what clears an orphan; with some, the other
    entries are kept as they are. ``notes`` collects the lines to say."""
    today = today or datetime.date.today()
    notes = notes if notes is not None else []
    pages = [parse_page(root, p) for p in page_paths(root)]
    wanted = None
    if only:
        wanted = set()
        for name in only:
            key = name if name.startswith(LIBRARY + "/") else f"{LIBRARY}/{name}"
            if key not in {p.path for p in pages}:
                raise LibraryError(f"{name} is not a page of the library")
            wanted.add(key)
    try:
        before = load_record(root)
    except LibraryError:
        if wanted is not None:
            raise
        before = {}                     # a whole stamp rebuilds a record it cannot read
    record = {} if wanted is None else dict(before)
    for page in pages:
        if wanted is None or page.path in wanted:
            now = fingerprint(root / page.path)
            was = before.get(page.path, {}).get("page")
            if was and was != now:
                notes.append(_keep_earlier(root, page.path, was, today))
            record[page.path] = {"page": now,
                                 "originals": {o: fingerprint(root / o) for o in page.originals if (root / o).is_file()}}
    record = {p: h for p, h in record.items() if p in {pg.path for pg in pages}}
    (root / RECORD).write_bytes(render_record(record))
    (root / START_PAGE).write_bytes(render_start(pages, history_entries(root)).encode("utf-8"))
    return findings(root)


